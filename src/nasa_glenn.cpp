const std::vector<Species>& allSpecies() {
    // built once (thread-safe): the anchor of the enthalpy and the standard entropy come from the polynomial of the first
    // interval at 298.15 K, extrapolated by 1.85 K for the species that start at 300 K
    static const std::vector<Species> table = [] {
        std::vector<Species> species;
        species.reserve(sizeof(kRows) / sizeof(kRows[0]));
        for (const Row& row : kRows) {
            Species s{row.name, row.composition, row.molarMass / 1000.0, row.formationEnthalpy, kIntervals + row.first,
                      row.count, 0.0, 0.0};
            const double lnT = std::log(kReferenceTemperature);
            s.polynomialH298 = kGasConstant * enthalpyOverR(s.intervals[0], kReferenceTemperature, lnT);
            s.standardEntropy = kGasConstant * entropyOverR(s.intervals[0], kReferenceTemperature, lnT);
            species.push_back(s);
        }
        return species;
    }();
    return table;
}

const Species* find(const std::string& name) {
    for (const Species& species : allSpecies())
        if (equalsNoCase(name, species.name)) return &species;
    return nullptr;
}

Point evaluate(const Species& species, double T) {
    if (!(T >= species.tMin() && T <= species.tMax()))
        throw std::out_of_range(std::string("NASA-Glenn data of ") + species.name + ": T = " + numberText(T) +
                                " K is outside the range " + numberText(species.tMin()) + " K to " +
                                numberText(species.tMax()) + " K");
    const Interval& iv = intervalOf(species, T);
    const double lnT = std::log(T);
    Point p;
    p.cp = kGasConstant * cpOverR(iv, T);
    p.dcp_dT = kGasConstant * dcpOverR(iv, T);
    p.h = species.formationEnthalpy + kGasConstant * enthalpyOverR(iv, T, lnT) - species.polynomialH298;
    p.s = kGasConstant * entropyOverR(iv, T, lnT);
    return p;
}

