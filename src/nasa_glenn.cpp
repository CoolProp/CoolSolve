double cpOverR(const Interval& iv, double T) {
    const double* a = iv.a;
    return (a[0] / T + a[1]) / T + a[2] + T * (a[3] + T * (a[4] + T * (a[5] + T * a[6])));
}

double dcpOverR(const Interval& iv, double T) {
    const double* a = iv.a;
    return -(2.0 * a[0] / T + a[1]) / (T * T) + a[3] + T * (2.0 * a[4] + T * (3.0 * a[5] + T * 4.0 * a[6]));
}

double enthalpyOverR(const Interval& iv, double T, double lnT) {
    const double* a = iv.a;
    return -a[0] / T + a[1] * lnT + a[2] * T +
           T * T * (a[3] / 2.0 + T * (a[4] / 3.0 + T * (a[5] / 4.0 + T * a[6] / 5.0))) + iv.b[0];
}

double entropyOverR(const Interval& iv, double T, double lnT) {
    const double* a = iv.a;
    return -(0.5 * a[0] / T + a[1]) / T + a[2] * lnT +
           T * (a[3] + T * (a[4] / 2.0 + T * (a[5] / 3.0 + T * a[6] / 4.0))) + iv.b[1];
}

/// The interval of T: the first whose upper end is above T, the last one above its upper end (a boundary belongs to the
/// interval that starts there). Below the first interval it is the first.
const Interval& intervalOf(const Species& species, double T) {
    int i = 0;
    while (i + 1 < species.intervalCount && T >= species.intervals[i].tHigh) ++i;
    return species.intervals[i];
}

std::string numberText(double v) {
    std::ostringstream oss;
    oss << std::setprecision(10) << v;
    return oss.str();
}

bool equalsNoCase(const std::string& a, const char* b) {
    size_t i = 0;
    for (; i < a.size() && b[i] != '\0'; ++i)
        if (std::tolower(static_cast<unsigned char>(a[i])) != std::tolower(static_cast<unsigned char>(b[i]))) return false;
    return i == a.size() && b[i] == '\0';
}

